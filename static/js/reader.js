/*
 * reader.js — the dictionary reader. Session 9 D2.
 *
 * No framework, no build step, no runtime on the server (invariants 1-4). The
 * whole thing is: fetch a gzipped index, decompress it, find a row, fetch the
 * ONE shard that row points at, render.
 *
 * WHY DECOMPRESSION IS EXPLICIT
 * Cloudflare Pages sets Content-Type from the file extension and does NOT attach
 * Content-Encoding: gzip to a .gz on disk, so the browser hands raw gzip bytes to
 * JSON.parse and fails. The decision and its rejected alternative are recorded in
 * tools/emit/gzip_shards.py. The same reason applies to the service worker: it
 * must NOT assume a header either.
 *
 * FONT: themes/copticref/static/fonts/Coptic.woff2 does not exist yet (see
 * fonts/README.md). .coptic below falls back to a system stack that covers
 * U+2C80..U+2CFF. Replace the stack when the subset font lands; do not ship a
 * webfont that has not been licence-checked.
 */
"use strict";

// ROOT-RELATIVE, leading slash.
//
// The first version was page-relative ("data/dist/dict/index.json.gz"). On
// /dict/ that resolves to /dict/data/dist/dict/index.json.gz, which 404s -- and
// worse, it can never match the service worker's cache key, which stores the
// absolute /data/dist/dict/index.json.gz. So the reader worked on no page and
// could not have worked offline even once the worker installed.
//
// Playwright found it as a 404 in the console. session 10 D1.
const INDEX_URL = "/data/dist/dict/index.json.gz";
const SHARD = (n) => `/data/dist/dict/shard-${String(n).padStart(3, "0")}.json.gz`;

/* ── gzip fetch ─────────────────────────────────────────────────────────── */
/* Delegated to the shared helper. Session 12 D0.
 *
 * This used to be a third copy of "fetch and inflate", and the copies had
 * drifted: this one sniffs, corpus.js sniffed, and read-csv.html inflated
 * unconditionally. read-csv.html was therefore still the pre-Session-11 bug and
 * would have thrown on Cloudflare Pages, which sends Content-Encoding: gzip.
 *
 * Kept as a named function because loadIndex/loadShard call it and because the
 * Playwright corpus tests reference it by name.
 */
function getJsonGz(url, opts) {
  if (typeof FetchJson === "undefined") {
    return Promise.reject(new Error(
      "fetch_json.js did not load: /js/fetch_json.js must be included before " +
      "reader.js. The dictionary cannot read its index without it."));
  }
  return FetchJson.json(url, opts);
}

/* ── state ──────────────────────────────────────────────────────────────── */
const shards = new Map();   // shard no -> parsed entries. Lazy, then cached.
let index = null;           // index.json.gz
let byKey = null;           // norm_key -> row
let shardPromise = new Map();

async function loadIndex() {
  if (index) return index;
  index = await getJsonGz(INDEX_URL);
  byKey = new Map();
  for (const r of index.rows) byKey.set(r.norm_key, r);
  installTables(index.casefold, index.strip_chars);
  if (index.collation_hash && window.__EXPECT_COLLATION__) {
    // A client can refuse an index built with a different alphabet rather than
    // silently sorting differently from the shards.
    const got = index.collation_hash;
    const want = window.__EXPECT_COLLATION__;
    if (want && got !== want) {
      console.warn(`[reader] index collation_hash ${got} != pinned ${want}`);
    }
  }
  return index;
}

async function loadShard(no) {
  if (shards.has(no)) return shards.get(no);
  if (shardPromise.has(no)) return shardPromise.get(no);
  const p = getJsonGz(SHARD(no)).then((b) => {
    shards.set(no, b.entries);
    shardPromise.delete(no);
    return b.entries;
  }).catch((e) => { shardPromise.delete(no); throw e; });
  shardPromise.set(no, p);
  return p;
}

// Capital -> small, loaded from index.json.gz's `casefold` table.
//
// The first version of this folded by RANGE ARITHMETIC -- subtract 8 from
// U+2C80..U+2C8F -- and the manual test caught it: U+2C81 (small alpha) became
// U+2C99, so every lookup missed. The folds are not uniform anyway: U+2C8B -> U+2C81
// is -8, while U+2C98 (MI) -> U+2C99 is +1. No offset works.
//
// So the table ships inside the index, generated by tools/emit/dict_index.py from
// Unicode names. One file owns the concept; the client does not re-derive it.
let casefold = null;   // Map<codePoint, small>
let strip = null;      // Set<codePoint> of combining marks to drop

/* Both tables come from index.json, generated by tools/emit/dict_index.py.
   `strip_chars` is derived from collate._IGN -- which is a set of Unicode
   CATEGORIES (Cf, Me, Mn), not code points -- so a client cannot derive it.
   Measured: nine lemmas were unreachable until this was added, all of them
   carrying U+FE26 or U+FE24, which sit outside every range anyone would guess. */
function installTables(casefoldTable, stripTable) {
  casefold = new Map();
  for (const [k, v] of Object.entries(casefoldTable || {})) {
    casefold.set(parseInt(k.replace("U+", ""), 16), v);
  }
  strip = new Set((stripTable || []).map((k) => parseInt(k.replace("U+", ""), 16)));
}

function normKey(s) {
  if (!casefold || !strip) {
    // Before the tables arrive, do only what is unambiguous: normalise. Guessing
    // a mark range is how the first version corrupted every small letter.
    return s.normalize("NFC");
  }
  let out = "";
  for (const ch of s.normalize("NFC")) {
    const cp = ch.codePointAt(0);
    if (strip.has(cp)) continue;                    // combining mark, per the collator
    out += casefold.get(cp) || ch;
  }
  return out;
}

/* ── render: the list ───────────────────────────────────────────────────── */
const esc = (s) => String(s ?? "").replace(/[&<>"]/g,
  (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

function dialectChips(dialects) {
  const ds = dialects || [];
  if (!ds.length) return "";
  const note = ds.length === 1 && ds[0] === "N"
    ? '<span class="note" title="Q4: no source recorded a dialect">not recorded</span>'
    : "";
  return ds.map((d) => `<span class="chip chip-${esc(d)}">${esc(d)}</span>`).join(" ")
       + note;
}

/* Rows by "<shard>-<offset>", the id the English index uses. Built once from the
   index rows the page already fetched, so resolving a Latin hit to a lemma costs
   no extra request. */
let byEntryId = null;

function entryIdMap() {
  if (!byEntryId) {
    byEntryId = new Map();
    for (const r of index.rows) byEntryId.set(`${r.shard}-${r.offset}`, r);
  }
  return byEntryId;
}

function renderList(query) {
  const q = normKey(query.trim());
  const rows = index.rows.filter((r) => !q || r.norm_key.startsWith(q));
  const shown = rows.slice(0, 300);
  const body = shown.map((r) => `
    <li>
      <button class="hit" data-key="${esc(r.norm_key)}">
        <span class="coptic lemma">${esc(r.lemma)}</span>
        <span class="gloss">${esc(r.gloss || (r.pos || []).join(", "))}</span>
        <span class="chips">${dialectChips(r.dialects)}</span>
      </button>
    </li>`).join("");
  const more = rows.length > shown.length
    ? `<p class="note">${rows.length - shown.length} more — refine the search.</p>` : "";
  document.getElementById("results").innerHTML =
    `<p class="count">${rows.length.toLocaleString()} headword${rows.length === 1 ? "" : "s"}</p>
     <ul class="hits">${body || '<li class="note">No headword starts with that.</li>'}</ul>${more}`;
  document.querySelectorAll("button.hit").forEach((b) =>
    b.addEventListener("click", () => show(b.dataset.key)));

  /* ── English path (Session 14 D2) ──────────────────────────────────────────
   *
   * `copper` returns 0 hits from Pagefind 1.5.2 even though 19 entries gloss it
   * "copper carbonate, azurite". Filed as PageFind/PageFind#1370. Until it is
   * fixed, Latin terms are looked up in a static inverted index and the matching
   * entries are merged into the same list, deduped on norm_key.
   *
   * Asynchronous, so the Coptic rows paint immediately and the English ones
   * arrive a tick later. The UI does not change: same markup, same buttons.
   */
  const raw = query.trim();
  const latin = (raw.match(/[A-Za-z][A-Za-z'\-]*/g) || []);
  if (!latin.length || typeof Search === "undefined") return;

  Search.englishTerms(raw)
    .then((ids) => {
      if (!ids.length) return;
      const extra = Search.resolve(ids, entryIdMap());
      const seen = new Set(rows.map((r) => r.norm_key));
      const merged = rows.concat(extra.filter((r) => !seen.has(r.norm_key)));
      if (merged.length === rows.length) return;      // nothing new
      renderRows(merged, query);
    })
    .catch(() => { /* degraded path: the Coptic results already on screen stand */ });
}

/** Draw a row list. Split out of renderList so the English merge can redraw. */
function renderRows(rows, query) {
  const shown = rows.slice(0, 300);
  const body = shown.map((r) => `
    <li>
      <button class="hit" data-key="${esc(r.norm_key)}">
        <span class="coptic lemma">${esc(r.lemma)}</span>
        <span class="gloss">${esc(r.gloss || (r.pos || []).join(", "))}</span>
        <span class="chips">${dialectChips(r.dialects)}</span>
      </button>
    </li>`).join("");
  const more = rows.length > shown.length
    ? `<p class="note">${rows.length - shown.length} more — refine the search.</p>` : "";
  document.getElementById("results").innerHTML =
    `<p class="count">${rows.length.toLocaleString()} entr${rows.length === 1 ? "y" : "ies"}` +
    `${query ? ` for "${esc(query.trim())}"` : ""}</p>
     <ul class="hits">${body || '<li class="note">Nothing found.</li>'}</ul>${more}`;
  document.querySelectorAll("button.hit").forEach((b) =>
    b.addEventListener("click", () => show(b.dataset.key)));
}

/* ── render: one entry ──────────────────────────────────────────────────── */
async function show(nk) {
  const row = byKey.get(nk);
  if (!row) return;
  const out = document.getElementById("entry");
  out.innerHTML = `<p class="note">Loading ${esc(row.lemma)} …</p>`;
  let entries;
  try {
    entries = await loadShard(row.shard);
  } catch (e) {
    out.innerHTML = `<p class="err">Could not load shard ${row.shard}: ${esc(e.message)}</p>`;
    return;
  }
  const e = entries[row.offset];
  if (!e) {
    out.innerHTML = `<p class="err">Offset ${row.offset} is past the end of shard ${row.shard}.</p>`;
    return;
  }

  const refs = (e.corpus_refs || []).map((r) => `
    <li>
      <!-- Session 10 D3: /corpus/<work>/ exists now, so this is a real link and
           the dictionary<->corpus loop closes both ways. It was a <span> for a
           session because inventing a route would have been a dead link. -->
      <a class="worklink" href="/corpus/${esc(r.work_slug || "")}/">${esc(r.work_title || r.work_slug)}</a>
      <span class="note">${r.occurrences} occurrence${r.occurrences === 1 ? "" : "s"}</span>
    </li>`).join("");

  const glosses = (e.glosses || []).map((g) => `
    <li>${esc(g.text)}${g.source ? ` <span class="note">— ${esc(g.source)}</span>` : ""}</li>`).join("");

  const attrs = (e.attributions || []).map((a) => `
    <li><code>${esc(a.field)}</code>: ${esc(a.changes || "")}
      ${a.source ? `<span class="note">— ${esc(a.source)}</span>` : ""}</li>`).join("");

  const forms = (e.forms || []).map((f) => `<li><span class="coptic">${esc(f.form)}</span></li>`).join("");
  const exs = (e.examples || []).map((x) => `<li>${esc(x.text || "")}</li>`).join("");

  out.innerHTML = `
    <h2 class="coptic">${esc(e.lemma)}</h2>
    <dl>
      <dt>Part of speech</dt><dd>${(e.pos || []).map(esc).join(", ")}
        ${(e.pos || []).includes("unknown")
          ? '<span class="note">not recorded by any source — shown, not hidden</span>' : ""}</dd>
      ${translitDisplay(e) ? `<dt>Transliteration</dt><dd>${esc(translitDisplay(e))}</dd>` : ""}
      <dt>Dialects</dt><dd>${dialectChips(e.dialects)}</dd>
    </dl>
    ${glosses ? `<h3>Glosses</h3><ul>${glosses}</ul>` : ""}
    ${e.etymology ? `<h3>Etymology</h3><p>${esc(e.etymology.text || e.etymology)}</p>` : ""}
    ${forms ? `<h3>Forms</h3><ul>${forms}</ul>` : ""}
    ${exs ? `<h3>Examples</h3><ul>${exs}</ul>` : ""}
    ${refs ? `<h3>In the corpus</h3><ul>${refs}</ul>` : ""}
    ${attrs ? `<h3>What we changed</h3><ul>${attrs}</ul>` : ""}
    <p class="note">Sources: ${(e.sources || []).map((s) => esc(s.id)).join(", ") || "—"}</p>`;
}

/* ── boot ───────────────────────────────────────────────────────────────── */
(async function boot() {
  const q = document.getElementById("q");
  const noscriptNote = document.getElementById("noscript-note");
  try {
    await loadIndex();
    if (noscriptNote) noscriptNote.hidden = true;
    renderList("");
    document.getElementById("count-all").textContent =
      `${index.entry_count.toLocaleString()} entries · ${index.rows.length.toLocaleString()} headwords`;
    let t;
    q.addEventListener("input", () => {
      clearTimeout(t);
      t = setTimeout(() => renderList(q.value), 120);
    });

    // Deep link: /dict/?q=<norm>.
    //
    // The corpus reader sends every clicked token here, so without this the
    // round-trip is a dead end — you land on the dictionary with an empty box and
    // no indication that a word was already chosen for you. Session 10 D3.
    //
    // Read AFTER loadIndex, because normKey needs the casefold/strip tables that
    // only exist once the index has arrived. Normalising early would fold
    // nothing and silently miss.
    const params = new URLSearchParams(location.search);
    const initial = (params.get("q") || "").trim();
    if (initial) {
      q.value = initial;
      renderList(initial);
      // Land on the entry, not the list: the point of the link is THIS word.
      const first = document.querySelector("#results button.hit");
      if (first) first.click();
      if (location.hash) {
        const target = document.querySelector(location.hash);
        if (target) target.scrollIntoView();
      }
    } else {
      q.focus();
    }
  } catch (e) {
    document.getElementById("results").innerHTML =
      `<p class="err">Could not load the dictionary index: ${esc(e.message)}</p>`;
  }
})();

