#!/usr/bin/env node
/*
 * tools/emit/sw_gen.mjs — the service worker. Session 9 D4.
 *
 * Written to the spec that has been sitting in this file since Session 7, which
 * said the thing that matters:
 *
 *   THE WORKER MUST NOT ASSUME Content-Encoding FOR A .gz.
 *   Cloudflare Pages sets Content-Type from the file extension and does not
 *   attach Content-Encoding to a .gz on disk. A worker that cached
 *   shard-003.json.gz and returned the response unchanged would hand raw gzip
 *   bytes to reader.js's JSON.parse -- but only on the SECOND visit, because the
 *   first visit fetches from the network and works fine. That is the worst kind
 *   of bug: it looks like a cache problem and it is a format problem.
 *
 * So: the cache stores the COMPRESSED bytes exactly as fetched, and reader.js
 * decompresses with DecompressionStream, on the first visit and every one after.
 * The worker is a byte pipe. It never inspects, never re-encodes, never guesses.
 *
 * BUDGETS
 *   precache  the shell + reader.js + styles.css + the whole index + shard-000,
 *            so a first-time reader who goes offline immediately can still look
 *            up one alphabet's worth of words.
 *   runtime   shards, LRU, evicted at 24 MB. 23 shards is ~1.9 MB total, so the
 *            cap is not reached by this dataset -- it is here because the
 *            dataset grows and a phone's storage does not.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const PUBLIC = path.join(ROOT, "public");
const VERSION = process.env.SW_VERSION || "v1";

/* Precache: the minimum for "I went offline and the dictionary still opens". */
const PRECACHE = [
  "/", "/dict/", "/dialects/", "/licences/",
  "/css/styles.css", "/js/reader.js",
  "/data/dist/dict/index.json.gz",
  "/data/dist/dict/shard-000.json.gz",
];

/* Runtime: everything else under these prefixes, cached on demand. */
const RUNTIME = ["/data/", "/pagefind/", "/licences/"];

const RUNTIME_MAX = 24 * 1024 * 1024;   // LRU ceiling

const sw = `/* Generated by tools/emit/sw_gen.mjs. Do not edit.
   Version ${VERSION}. */
const PRECACHE = ${JSON.stringify(PRECACHE)};
const RUNTIME_PREFIXES = ${JSON.stringify(RUNTIME)};
const RUNTIME_MAX = ${RUNTIME_MAX};
const CACHE = "copticref-${VERSION}";

self.addEventListener("install", (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    // addAll is atomic-ish: if ANY url 404s the whole install rejects and the
    // worker never activates, rather than activating half-cached and failing on
    // first use. Session 9 D7 asserts this by precaching a missing url.
    await c.addAll(PRECACHE);
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) {
      if (k !== CACHE) await caches.delete(k);
    }
    await self.clients.claim();
  })());
});

/* LRU by insertion order: Cache keys() is ordered, so re-putting a key moves it
   to the end and trimming from the front evicts the least recently used. */
async function trim(c) {
  const keys = await c.keys();
  let total = 0;
  for (const k of keys) total += (await c.match(k))?.blob?.().then ? 0 : 0;
  let bytes = 0;
  for (const k of keys) {
    const r = await c.match(k);
    if (r) bytes += Number(r.headers.get("content-length") || 0);
  }
  while (bytes > RUNTIME_MAX && keys.length) {
    const victim = keys.shift();
    const r = await c.match(victim);
    if (r) bytes -= Number(r.headers.get("content-length") || 0);
    await c.delete(victim);
  }
}

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  e.respondWith((async () => {
    // Cache first for everything we own. For a .gz this returns the COMPRESSED
    // bytes unchanged, which is what reader.js expects -- it decompresses
    // explicitly. We do not re-encode, do not set Content-Encoding, and do not
    // consult the network for a body we already hold.
    const cached = await caches.match(req, { ignoreSearch: true });
    if (cached) {
      if (RUNTIME_PREFIXES.some((p) => url.pathname.startsWith(p))) {
        const c = await caches.open(CACHE);
        await c.put(req, cached.clone());     // touch: moves to the LRU end
      }
      return cached;
    }

    try {
      const res = await fetch(req);
      if (res.ok && RUNTIME_PREFIXES.some((p) => url.pathname.startsWith(p))) {
        const c = await caches.open(CACHE);
        await c.put(req, res.clone());
        trim(c);
      }
      return res;
    } catch (err) {
      // Offline and not cached: for a navigation, fall back to the shell so the
      // reader shows its "offline" state rather than the browser's error page.
      if (req.mode === "navigate") {
        const shell = await caches.match("/dict/");
        if (shell) return shell;
      }
      throw err;
    }
  })());
});

/* The page asks this to show an offline indicator. Cheap, and it is the only
   way a reader learns WHY a word is missing rather than assuming the site is
   broken. */
self.addEventListener("message", (e) => {
  if (e.data === "status") {
    e.source && e.source.postMessage({ online: navigator.onLine === true, version: CACHE });
  }
});
`;

if (!fs.existsSync(PUBLIC)) {
  console.error("[sw_gen] public/ does not exist. Run tools/build.py first.");
  process.exit(1);
}
const missing = PRECACHE.filter((p) => !fs.existsSync(path.join(PUBLIC, p.replace(/^\//, ""))));
if (missing.length) {
  // Refuse rather than emit a worker whose install() rejects on first visit.
  console.error(`[sw_gen] refusing: ${missing.length} precache url(s) do not exist:`);
  for (const m of missing) console.error(`  - ${m}`);
  process.exit(1);
}

fs.writeFileSync(path.join(PUBLIC, "sw.js"), sw);
const size = Buffer.byteLength(sw);
console.error(`[sw_gen] wrote public/sw.js (${(size / 1024).toFixed(1)} KiB), ` +
  `${PRECACHE.length} precached, runtime cap ${(RUNTIME_MAX / 1048576).toFixed(0)} MiB`);
