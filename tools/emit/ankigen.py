#!/usr/bin/env python3
"""tools/emit/ankigen.py — export the quiz and drill banks as Anki decks.

LICENCE: project code, Apache-2.0.

Session 22 D2 / C4. The site teaches; Anki preserves. A learner who finishes
a course flow should be able to carry the same items into the SRS they
already use, without an account, a server, or a plugin.

Two decks, generated at build time from the SAME banks the browser serves
(quiz banks under data/dist/quiz/, cloze banks under data/dist/drill/) —
one source of truth, two presentations. Anki is a zip with a sqlite
collection; genanki (MIT, pinned 0.13.1 in the venv) writes the format.
Output goes to work/anki/ — gitignored pipeline intermediates, copied into
public/downloads/anki/ by tools/build.py. (Not data/dist/: Hugo's data
loader walks everything under data/ and a binary .apkg fails its
unmarshal.)

  quiz.apkg    every quiz item in every bank — all 19 banks, 959 cards:
               English<->Coptic both directions, transliteration, lemma,
               part-of-speech and dialect identification, verse matching,
               all three difficulties plus the unband verse set. Front =
               the prompt, back = the correct choice (Coptic-script
               answers rendered in the Coptic face) plus the dictionary's
               rank-1 gloss where the answer's entry resolves.
  drill.apkg   every cloze drill item, one card per verse. Front = the verse
               with the blank, back = the removed form, its lemma, and a link
               to the dictionary entry on the production site.

Session 23 D1 replaced the Session 22 subset (vocab.apkg, 300 English<->Coptic
cards only) with the full 959: every bank item is a resolvable question with
one correct choice, 959/959 convert, and the package lands near 640 KB — far
inside any sane size budget. The deck and file were renamed with it, because
"vocabulary" was no longer a true description.

GUIDS are derived from the bank item id (genanki.guid_for), never from field
content: two banks can legitimately share a prompt ("fifty" appears at more
than one difficulty), and a content hash would silently merge them.

Decks are CC BY-SA 4.0, same as the site; attribution to CCL, Kaikki, and
Coptic Scriptorium is in the deck description and on the /anki/ page.
"""
from __future__ import annotations

import argparse
import gzip
import html
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

import safeio  # noqa: E402

try:
    import genanki
except ImportError as e:  # pragma: no cover - environment, not logic
    raise SystemExit(
        "ankigen: genanki is required (pip install genanki==0.13.1). "
        f"It is a BUILD-time dependency only; nothing at runtime uses it. ({e})")

QUIZ_DIR = ROOT / "data" / "dist" / "quiz"
DRILL_DIR = ROOT / "data" / "dist" / "drill"
# NOT under data/: Hugo's data loader walks everything below data/ and a
# binary .apkg fails its unmarshal (Session 22 first build: "unmarshal of
# format \"\" is not supported"). work/ is the gitignored pipeline-
# intermediates tree; build.py copies the decks into public/downloads/anki/.
OUT_DIR = ROOT / "work" / "anki"

# Fixed IDs: they must be stable forever (Anki merges by model/deck id) and
# unique across the Anki universe. Chosen once, documented here, never
# regenerated. The quiz deck/model keep the Session 22 vocab IDs: same deck
# id + same note guids means anyone who imported the 300-card vocab.apkg
# gets an in-place upgrade, not a duplicate deck.
QUIZ_DECK_ID = 2059400110
DRILL_DECK_ID = 2059400111
QUIZ_MODEL_ID = 2059400210
DRILL_MODEL_ID = 2059400211

# Canonical host: hugo.yaml's baseURL and the sitemap are coptic.re; cards
# that deep-link the dictionary go to the same host the sitemap claims.
SITE_BASE = "https://coptic.re"
ATTRIBUTION = ("Sources: CCL, Kaikki, Coptic Scriptorium. "
               "Licence: CC BY-SA 4.0, same as the site. "
               "Generated by tools/emit/ankigen.py from the published banks.")

QUIZ_MODEL = genanki.Model(
    QUIZ_MODEL_ID,
    "Coptic Reference Quiz Items",
    fields=[{"name": "Front"}, {"name": "Back"}, {"name": "Notes"}],
    templates=[{
        "name": "Recognition",
        "qfmt": "{{Front}}",
        "afmt": "{{FrontSide}}<hr id=answer>{{Back}}",
    }],
    sort_field_index=0,
    css="""\
.card { font-family: system-ui, sans-serif; font-size: 20px; text-align: center; color: black; background: white; }
.coptic { font-family: "Coptic", "Segoe UI Historic", "Noto Sans Coptic", "New Athena Unicode", serif; }
.notes { font-size: 12px; color: #666; }
""",
)

DRILL_MODEL = genanki.Model(
    DRILL_MODEL_ID,
    "Coptic Reference Cloze",
    fields=[{"name": "Front"}, {"name": "Back"}, {"name": "Notes"}],
    templates=[{
        "name": "Fill the gap",
        "qfmt": "{{Front}}",
        "afmt": "{{FrontSide}}<hr id=answer>{{Back}}",
    }],
    sort_field_index=0,
    css="""\
.card { font-family: system-ui, sans-serif; font-size: 18px; text-align: center; color: black; background: white; }
.coptic { font-family: "Coptic", "Segoe UI Historic", "Noto Sans Coptic", "New Athena Unicode", serif; line-height: 1.8; }
.notes { font-size: 12px; color: #666; }
""",
)


def _load_gz(path: pathlib.Path):
    return json.loads(gzip.decompress(path.read_bytes()))


def _coptic_script(s: str) -> bool:
    """True if the string carries a Coptic code point (Unicode block
    U+2C80..2CF3, plus Coptic Extended-A). Decides which card face gets the
    Coptic font class — presentation only, never which answer is correct."""
    return any("Ⲁ" <= ch <= "ⳳ" or "Ⳡ" <= ch <= "Ⳬ" for ch in s)


def _entry_index() -> dict[str, dict]:
    """entry_id -> {gloss, norm_key, lemma} from every dict shard."""
    index: dict[str, dict] = {}
    shards = sorted((ROOT / "data" / "dist" / "dict").glob("shard-*.json.gz"))
    if not shards:
        raise SystemExit("ankigen: no dict shards; run the merge pipeline first")
    for shard in shards:
        data = _load_gz(shard)
        for e in data.get("entries", []):
            gloss = ""
            for g in e.get("glosses") or []:
                if isinstance(g, dict) and g.get("lang") == "en" and g.get("text"):
                    if g.get("rank") == 1:
                        gloss = g["text"].strip()
                        break
                    if not gloss:
                        gloss = g["text"].strip()
            index[e.get("id") or ""] = {
                "gloss": gloss,
                "norm_key": e.get("norm_key") or "",
                "lemma": e.get("lemma") or "",
            }
    return index


def _vocab_notes(bank: str, item: dict) -> str:
    return (f"Bank: {bank} · id {item.get('id', '?')} · {ATTRIBUTION}")


def build_quiz(entries: dict[str, dict]) -> genanki.Package:
    deck = genanki.Deck(QUIZ_DECK_ID, "Coptic Reference::Quiz Items")
    deck.description = (
        "All quiz banks from coptic.re — one card per item. "
        + ATTRIBUTION)
    banks = sorted(QUIZ_DIR.glob("*.json.gz"))
    if not banks:
        raise SystemExit(f"ankigen: no quiz banks under {QUIZ_DIR}")
    made = 0
    for bank_path in banks:
        bank = bank_path.name.replace(".json.gz", "")
        for item in _load_gz(bank_path):
            choices = item.get("choices") or []
            correct_i = item.get("correct")
            if not isinstance(correct_i, int) or not (0 <= correct_i < len(choices)):
                continue  # a bank item without a resolvable answer is not a card
            answer = choices[correct_i]
            prompt_text = item.get("prompt") or ""
            prompt = (f'<span class="coptic">{html.escape(prompt_text)}</span>'
                      if _coptic_script(prompt_text) else html.escape(prompt_text))
            meta = item.get("source") or {}
            entry = entries.get(meta.get("entry_id") or "", {})
            gloss = html.escape(entry.get("gloss") or "")
            answer_html = html.escape(answer)
            if _coptic_script(answer):
                answer_html = f'<span class="coptic">{answer_html}</span>'
            back_bits = [answer_html]
            if gloss:
                back_bits.append(f"<div class=\"notes\">{gloss}</div>")
            note = genanki.Note(
                model=QUIZ_MODEL,
                fields=[prompt, "<br>".join(back_bits),
                        _vocab_notes(bank, item)],
                guid=genanki.guid_for("coptic-ref-vocab", item.get("id") or
                                      f"{bank}-{made}"),
            )
            deck.add_note(note)
            made += 1
    if made == 0:
        raise SystemExit("ankigen: quiz deck produced 0 notes")
    print(f"[ankigen] quiz: {made} card(s) from {len(banks)} bank(s)")
    return genanki.Package(deck)


def build_drill(entries: dict[str, dict]) -> genanki.Package:
    deck = genanki.Deck(DRILL_DECK_ID, "Coptic Reference::Cloze Drills")
    deck.description = (
        "Cloze drills from the parsed corpus on coptic.re, one card per verse. "
        + ATTRIBUTION)
    by_lemma: dict[str, dict] = {}
    for e in entries.values():
        # First entry wins on a shared lemma; the link only needs one id.
        by_lemma.setdefault(e.get("lemma") or "", e)
    banks = sorted(DRILL_DIR.glob("cloze-*.json.gz"))
    if not banks:
        raise SystemExit(f"ankigen: no cloze banks under {DRILL_DIR}")
    made = 0
    for bank_path in banks:
        work = _load_gz(bank_path)
        work_slug = work.get("work_slug") or bank_path.stem
        for item in work.get("items") or []:
            tokens = item.get("tokens") or []
            blank = item.get("blank")
            if not isinstance(blank, int) or not (0 <= blank < len(tokens)):
                continue
            front_tokens = list(tokens)
            front_tokens[blank] = "[ …… ]"
            ref = item.get("ref") or work_slug
            front = (f'<div class="coptic">{" ".join(front_tokens)}</div>'
                     f'<div class="notes">{html.escape(ref)}</div>')
            src = item.get("source") or {}
            form = src.get("removed_form") or tokens[blank]
            lemma = src.get("lemma") or ""
            entry = by_lemma.get(lemma)
            back_bits = [f'<span class="coptic">{html.escape(form)}</span>']
            if lemma and lemma != form:
                back_bits.append(f"<div>lemma: {html.escape(lemma)}</div>")
            if entry and entry.get("norm_key"):
                url = f"{SITE_BASE}/dict/?q={html.escape(entry['norm_key'], quote=True)}"
                back_bits.append(
                    f'<div class="notes"><a href="{url}">dictionary entry</a></div>')
            note = genanki.Note(
                model=DRILL_MODEL,
                fields=[front, "<br>".join(back_bits),
                        f"Bank: cloze-{work_slug} · id {item.get('id', '?')} · "
                        + ATTRIBUTION],
                guid=genanki.guid_for("coptic-ref-cloze", item.get("id") or
                                      f"{work_slug}-{made}"),
            )
            deck.add_note(note)
            made += 1
    if made == 0:
        raise SystemExit("ankigen: drill deck produced 0 notes")
    print(f"[ankigen] drill: {made} card(s) from {len(banks)} bank(s)")
    return genanki.Package(deck)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="emit the /anki/ decks")
    ap.parse_args(argv)

    entries = _entry_index()
    if len(entries) < 1000:
        raise SystemExit(f"ankigen: entry index has only {len(entries)} "
                         f"entries; refusing to emit thin decks")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    # genanki writes the file itself; write to a tmp name and rename so a
    # half-written zip can never be the published artefact (Rule 3 spirit).
    for name, package in (("quiz.apkg", build_quiz(entries)),
                          ("drill.apkg", build_drill(entries))):
        final = OUT_DIR / name
        tmp = final.with_suffix(".apkg.tmp")
        package.write_to_file(str(tmp))
        payload = tmp.read_bytes()
        tmp.unlink()
        safeio.write_verified(final, payload, compress=False)
        print(f"[ankigen] {name}: {final.stat().st_size} B")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
